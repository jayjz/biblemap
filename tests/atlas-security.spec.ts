import { test, expect } from "@playwright/test";

for (const sourceKind of ["inline", "tilejson"] as const) {
  test(`Atlas preserves attribution and rejects adjacent executable attributes from ${sourceKind}`, async ({ page }) => {
    const errors: string[] = [];
    const failed: string[] = [];
    const workerResponses: { url: string; status: number; contentType: string }[] = [];
    page.on("pageerror", error => errors.push(error.message));
    page.on("requestfailed", request => failed.push(request.url()));
    page.on("response", response => {
      if (response.url().includes("maplibre-gl-") && response.url().endsWith(".mjs")) workerResponses.push({ url: response.url(), status: response.status(), contentType: response.headers()["content-type"] });
    });
    const attribution = '<a href="https://example.org/rights">Fixture attribution</a><details open onload="1" ontoggle="window.__atlasAttributionExecuted=1">Fixture disclosure</details><iframe title="Fixture" srcdoc="&lt;script&gt;parent.__atlasSrcdocExecuted=1&lt;/script&gt;"></iframe>';
    await page.route("https://basemaps.cartocdn.com/gl/dark-matter-gl-style/style.json", route => route.fulfill({ json: {
      version: 8,
      sources: sourceKind === "inline" ? { fixture: { type: "geojson", attribution, data: { type: "FeatureCollection", features: [{ type: "Feature", geometry: { type: "Point", coordinates: [35, 32] }, properties: {} }] } } } : { fixture: { type: "raster", url: "https://atlas-fixture.invalid/tilejson.json", tileSize: 256 } },
      layers: [{ id: "background", type: "background", paint: { "background-color": "#102020" } }, sourceKind === "inline" ? { id: "fixture", type: "circle", source: "fixture" } : { id: "fixture", type: "raster", source: "fixture" }],
    } }));
    await page.route("https://atlas-fixture.invalid/tilejson.json", route => route.fulfill({ json: { tilejson: "3.0.0", attribution, tiles: ["https://atlas-fixture.invalid/{z}/{x}/{y}.png"], minzoom: 0, maxzoom: 0 } }));
    await page.route("https://atlas-fixture.invalid/**/*.png", route => route.fulfill({ contentType: "image/png", body: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=", "base64") }));
    await page.goto("/explore/");
    const credit = page.locator(".maplibregl-ctrl-attrib a", { hasText: "Fixture attribution" });
    await expect(credit).toHaveAttribute("href", "https://example.org/rights");
    // Attribution is generated by an active source, not an unexecuted sanitizer fixture.
    expect(await page.evaluate(() => Reflect.get(window, "__atlasAttributionExecuted"))).toBeUndefined();
    expect(await page.evaluate(() => Reflect.get(window, "__atlasSrcdocExecuted"))).toBeUndefined();
    await expect(page.locator(".maplibregl-ctrl-attrib details[ontoggle], .maplibregl-ctrl-attrib details[onload]")).toHaveCount(0);
    await expect(page.locator(".maplibregl-ctrl-attrib iframe, .maplibregl-ctrl-attrib [srcdoc]")).toHaveCount(0);
    await expect.poll(() => workerResponses.length).toBeGreaterThan(0);
    for (const response of workerResponses) {
      expect(response.status, response.url).toBe(200);
      expect(response.contentType, response.url).toContain("javascript");
    }
    await page.setViewportSize({ width: 960, height: 720 });
    await expect(page.locator(".maplibregl-canvas")).toBeVisible();
    expect(errors).toEqual([]);
    expect(failed.filter(url => url.includes("atlas-fixture") || url.includes("/_next/"))).toEqual([]);
  });
}
