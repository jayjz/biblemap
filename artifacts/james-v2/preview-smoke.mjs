import { chromium, expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
const url = process.argv[2];
if (!url?.startsWith('https://biblemap-')) throw new Error('Provide the verified James preview URL');
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH });
const page = await browser.newPage({ viewport: { width: 390, height: 1000 }, reducedMotion: 'reduce', hasTouch: true });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('requestfailed', r => errors.push(r.url()));
page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); });
const response = await page.goto(url);
await expect(page.locator('#james-title')).toBeVisible({ timeout: 15000 });
await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', /noindex/);
await page.getByRole('link', { name: '3 Jerusalem', exact: true }).tap();
await expect(page.locator('#jerusalem img')).toHaveJSProperty('naturalWidth', 768);
await page.screenshot({ path: 'artifacts/james-v2/preview-jerusalem-390.jpg', quality: 85 });
await page.getByRole('button', { name: 'Antioch · disagreement', exact: true }).tap();
await expect(page.locator('#relationship-dispute')).toContainText('not Jerusalem');
await page.getByRole('link', { name: '4 The record', exact: true }).tap();
await page.screenshot({ path: 'artifacts/james-v2/preview-record-390.jpg', quality: 85 });
await page.locator('#record summary').filter({ hasText: 'Citizens object.' }).tap();
await expect(page.locator('#record').getByText(/In the received text, James is identified/)).toBeVisible();
await writeFile('artifacts/james-v2/preview-observations.json', JSON.stringify({ url: page.url(), status: response.status(), errors }, null, 2));
await browser.close();
expect(errors).toEqual([]);
