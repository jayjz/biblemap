import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const base = process.env.PLAYWRIGHT_BASE_URL ?? 'http://127.0.0.1:4193';
const folder = 'artifacts/james-v2/interactions';
await mkdir(folder, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH });
const observations = [];
for (const width of [1440, 768, 390, 320]) {
  const page = await browser.newPage({ viewport: { width, height: 1000 }, reducedMotion: 'reduce', hasTouch: width <= 390 });
  await page.goto(`${base}/human-story/james/#jerusalem`);
  await page.getByRole('button', { name: 'Antioch · disagreement', exact: true }).click();
  await expect(page.locator('#relationship-dispute')).toBeVisible();
  await page.locator('#relationship-dispute').evaluate(el => el.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: `${folder}/antioch-${width}.jpg`, quality: 85 });
  await page.getByRole('button', { name: 'Compare surviving witnesses', exact: true }).click();
  await page.getByRole('button', { name: 'Acts', exact: true }).click();
  await page.screenshot({ path: `${folder}/witnesses-${width}.jpg`, quality: 85 });
  await page.keyboard.press('Escape');
  await page.getByRole('link', { name: '4 The record', exact: true }).click();
  const objection = page.locator('#record summary').filter({ hasText: 'Citizens object.' });
  await objection.click();
  await objection.evaluate(el => el.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: `${folder}/objections-${width}.jpg`, quality: 85 });
  await page.locator('#record').evaluate(el => window.scrollTo(0, el.offsetTop - innerHeight * .5));
  await page.screenshot({ path: `${folder}/city-to-record-${width}.jpg`, quality: 85 });
  await page.getByRole('link', { name: '5 What remained', exact: true }).click();
  const memory = page.locator('#remained summary').filter({ hasText: 'Hegesippus → Eusebius' });
  await memory.click();
  await memory.evaluate(el => el.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: `${folder}/transmission-${width}.jpg`, quality: 85 });
  await page.getByRole('link', { name: '3 Jerusalem', exact: true }).click();
  await page.addStyleTag({ content: 'p, a, button, summary { font-size: 200% !important; }' });
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.getByRole('link', { name: '3 Jerusalem', exact: true }).click();
  const overflow = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth, elements: [...document.querySelectorAll('body *')].filter(el => { const r=el.getBoundingClientRect(); return r.width && (r.right > innerWidth+1 || r.left < -1) && getComputedStyle(el).position !== 'absolute'; }).map(el => ({ tag: el.tagName, class: el.className, text: el.textContent.slice(0,90), width: el.getBoundingClientRect().width })).slice(0,20) }));
  observations.push({ width, enlargedText: overflow });
  await page.screenshot({ path: `${folder}/text-200-${width}.jpg`, quality: 85 });
  await page.close();
}
const page = await browser.newPage({ viewport: { width: 390, height: 1000 }, reducedMotion: 'reduce' });
await page.route(/\/media\/james\/.*\.webp$/, route => route.abort());
await page.goto(`${base}/human-story/james/#jerusalem`);
await page.screenshot({ path: `${folder}/image-failure-390.jpg`, quality: 85 });
await writeFile(`${folder}/observations.json`, JSON.stringify(observations, null, 2));
await browser.close();
